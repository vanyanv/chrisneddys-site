/**
 * Bakes the static half of the LA map into `public/map-base.svg`.
 *
 * Why a file and not inline SVG: the geometry is ~94 KB of path data that never
 * changes between pages or between builds. Inlined, it shipped twice on every
 * request to `/` and `/locations/` — once in the HTML and once more in the RSC
 * flight payload, because the canvas is a Server Component rendered inside a
 * client tree. As a file it is fetched once, cached by CloudFront and the
 * browser, and shared by both pages.
 *
 * Only pure geometry moves out. Everything that needs a brand token or the
 * self-hosted mono face at runtime — street labels, freeway shields, the scale
 * bar, the north arrow, the ODbL attribution — stays inline in
 * `src/components/locations/LocationsMapCanvas.tsx`, drawn on top of this file
 * in the same viewBox.
 *
 * Run after any change to `src/data/laGeoPaths.ts`, `src/data/laGeo.ts`, the
 * map colour tokens in `src/styles/counter.css`, or the `.cne-map-*`
 * stroke-widths in `src/styles/globals.css`:
 *
 *     node scripts/build-map-base.mjs
 *
 * © OpenStreetMap contributors, ODbL. The attribution is drawn by the canvas
 * component and is required — do not remove it.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const paths = readFileSync(join(root, "src/data/laGeoPaths.ts"), "utf8");
const geo = readFileSync(join(root, "src/data/laGeo.ts"), "utf8");
const tokens = readFileSync(join(root, "src/styles/counter.css"), "utf8");
const globalsCss = readFileSync(join(root, "src/styles/globals.css"), "utf8");

/** Pull `export const <name> = "<path data>";` out of laGeoPaths.ts. */
function pathConst(name) {
  const m = paths.match(new RegExp(`export const ${name} = "([^"]+)";`));
  if (!m) throw new Error(`laGeoPaths.ts: could not read ${name}`);
  return m[1];
}

/** Pull a `--a-*` colour out of the :root block in counter.css. */
function token(name) {
  const m = tokens.match(new RegExp(`--${name}:\\s*([^;]+);`));
  if (!m) throw new Error(`counter.css: could not read --${name}`);
  return m[1].trim();
}

/**
 * Pull `stroke-width` out of a `.cne-map-<name>` rule in globals.css, so the
 * generated SVG's line weights can never drift from what the on-page overlay
 * (drawn by the same class names, in LocationsMapCanvas) actually renders.
 */
function strokeWidth(name) {
  const rule = globalsCss.match(new RegExp(`\\.cne-map-${name}\\s*\\{([^}]*)\\}`));
  if (!rule) throw new Error(`globals.css: could not find .cne-map-${name}`);
  const m = rule[1].match(/stroke-width:\s*([0-9.]+)/);
  if (!m) throw new Error(`globals.css: .cne-map-${name} has no stroke-width`);
  return m[1];
}

/** The viewBox has to match `mapBox` exactly or the pins land in the wrong place. */
function box(key) {
  const m = geo.match(new RegExp(`\\b${key}:\\s*([0-9.]+)`));
  if (!m) throw new Error(`laGeo.ts: could not read mapBox.${key}`);
  return Number(m[1]);
}

const w = box("w");
const h = box("h");

const motorway = pathConst("motorwayPath");
const water = pathConst("waterPath");
const river = pathConst("riverPath");
const streets = [...paths.matchAll(/\bd: "([^"]+)"/g)].map((m) => m[1]);
if (streets.length === 0) throw new Error("laGeoPaths.ts: no namedStreets geometry found");

/**
 * The style block mirrors `.cne-map-*` in src/styles/globals.css with the token
 * values resolved, because an <img>-loaded SVG is its own document and cannot
 * see the page's custom properties. The site has a single palette — no dark
 * mode — so resolving them here costs nothing.
 */
const css = [
  `.w{fill:${token("a-water")};stroke:none}`,
  `.r{fill:none;stroke:${token("a-water")};stroke-width:${strokeWidth("river")};stroke-linecap:round}`,
  `.b{fill:none;stroke:${token("a-blvd")};stroke-width:${strokeWidth("blvd")};stroke-linecap:round;stroke-linejoin:round}`,
  `.fc{fill:none;stroke:${token("a-fwycase")};stroke-width:${strokeWidth("fwy-case")};stroke-linecap:round;stroke-linejoin:round}`,
  `.f{fill:none;stroke:${token("a-fwy")};stroke-width:${strokeWidth("fwy")};stroke-linecap:round;stroke-linejoin:round}`,
].join("");

/**
 * Freeways are one path drawn twice: black casing under brand yellow. The
 * geometry lives in <defs> without a class of its own, so each <use> can hand
 * it stroke, stroke-width and fill by inheritance — which is what the inline
 * version could not do, and why it carried the 31 KB motorway path twice.
 */
const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">` +
  `<!-- Generated by scripts/build-map-base.mjs from src/data/laGeoPaths.ts. Do not edit by hand. -->` +
  `<!-- Map data © OpenStreetMap contributors, ODbL. -->` +
  `<style>${css}</style>` +
  `<defs><path id="fw" d="${motorway}"/></defs>` +
  `<rect width="${w}" height="${h}" fill="${token("a-mapbg")}"/>` +
  `<path class="w" d="${water}"/>` +
  `<path class="r" d="${river}"/>` +
  streets.map((d) => `<path class="b" d="${d}"/>`).join("") +
  `<use href="#fw" class="fc"/>` +
  `<use href="#fw" class="f"/>` +
  `</svg>\n`;

const out = join(root, "public/map-base.svg");
writeFileSync(out, svg);
console.log(`public/map-base.svg — ${svg.length} bytes, ${streets.length} named streets`);
